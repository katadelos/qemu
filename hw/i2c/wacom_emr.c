struct WacomEMRState {
    I2CSlave parent_obj;
    uint8_t command[32];
    uint8_t command_len;
    uint8_t response[1024];
    uint16_t response_len;
    uint16_t response_pos;
    uint8_t report_rate;
    bool sending;
    bool reset_level;
    bool asleep;
    qemu_irq irq;
    qemu_irq pen_detect;
    uint64_t queries;
    uint64_t descriptor_reads;
    uint64_t resets;
    uint64_t sleep_commands;
    uint64_t unsupported_commands;
};

static void wacom_response(WacomEMRState *s, const uint8_t *data, size_t len)
{
    assert(len <= sizeof(s->response));
    memcpy(s->response, data, len);
    s->response_len = len;
    s->response_pos = 0;
}

static void wacom_execute(WacomEMRState *s)
{
    const uint8_t *c = s->command;
    unsigned len = s->command_len;

    s->sending = false;
    if (!len) {
        return;
    }
    if (len == 2 && c[0] == 1 && c[1] == 0) {
        wacom_response(s, wacom_descriptor, sizeof(wacom_descriptor));
        s->descriptor_reads++;
    } else if (len == 2 && c[0] == 2 && c[1] == 0) {
        wacom_response(s, wacom_report_descriptor, sizeof(wacom_report_descriptor));
    } else if (len == 2 && c[0] == 5 && c[1] == 0) {
        /* The query's second I2C write selects the prepared data register. */
        s->response_pos = 0;
    } else if (len == 4 && c[0] == 4 && c[1] == 0 &&
               c[2] == 0x33 && c[3] == 2) {
        wacom_response(s, wacom_features, sizeof(wacom_features));
        s->queries++;
    } else if (len == 4 && c[0] == 4 && c[1] == 0 &&
               c[2] == 0 && c[3] == 1) {
        const uint8_t reset_response[2] = { 0, 0 };
        s->asleep = false;
        s->report_rate = 3;
        wacom_response(s, reset_response, sizeof(reset_response));
        s->resets++;
    } else if (len == 4 && c[0] == 4 && c[1] == 0 &&
               c[2] <= 1 && c[3] == 8) {
        s->asleep = c[2];
        s->response_len = s->response_pos = 0;
        s->sleep_commands++;
    } else if (len == 7 && !memcmp(c, "\x04\x00\x3f\x02\x19\x05\x00", 7)) {
        const uint8_t rate[4] = { 4, 0, 25, s->report_rate };
        wacom_response(s, rate, sizeof(rate));
    } else if (len == 11 &&
               !memcmp(c, "\x04\x00\x3f\x03\x19\x05\x00\x04\x00\x19", 10) &&
               (c[10] == 1 || c[10] == 3 || c[10] == 5 || c[10] == 6)) {
        s->report_rate = c[10];
        s->response_len = s->response_pos = 0;
    } else {
        s->unsupported_commands++;
        s->response_len = s->response_pos = 0;
        qemu_log_mask(LOG_UNIMP, "wacom-emr: unsupported command length %u %02x %02x %02x %02x\n",
                      len, c[0], c[1], c[2], c[3]);
    }
    s->command_len = 0;
}

static int wacom_send(I2CSlave *i2c, uint8_t data)
{
    WacomEMRState *s = WACOM_EMR(i2c);
    if (!s->reset_level || s->command_len == sizeof(s->command)) {
        return -1;
    }
    s->command[s->command_len++] = data;
    return 0;
}

static uint8_t wacom_recv(I2CSlave *i2c)
{
    WacomEMRState *s = WACOM_EMR(i2c);
    return s->response_pos < s->response_len ?
        s->response[s->response_pos++] : 0;
}

static int wacom_event(I2CSlave *i2c, enum i2c_event event)
{
    WacomEMRState *s = WACOM_EMR(i2c);
    if (s->sending) {
        wacom_execute(s);
    }
    if (event == I2C_START_SEND) {
        memset(s->command, 0, sizeof(s->command));
        s->command_len = 0;
        s->sending = true;
    } else if (event == I2C_START_RECV) {
        s->response_pos = 0;
    }
    return 0;
}

static void wacom_reset(DeviceState *dev)
{
    WacomEMRState *s = WACOM_EMR(dev);
    s->command_len = s->response_len = s->response_pos = 0;
    s->sending = s->asleep = false;
    s->report_rate = 3;
    qemu_set_irq(s->irq, 1);
    qemu_set_irq(s->pen_detect, 1);
}

static void wacom_gpio_reset(void *opaque, int line, int level)
{
    WacomEMRState *s = opaque;
    if (!level && s->reset_level) {
        wacom_reset(DEVICE(s));
        s->resets++;
    }
    s->reset_level = !!level;
}

static int wacom_post_load(void *opaque, int version)
{
    WacomEMRState *s = opaque;
    if (s->command_len > sizeof(s->command) ||
        s->response_len > sizeof(s->response) ||
        s->response_pos > s->response_len) {
        return -EINVAL;
    }
    qemu_set_irq(s->irq, 1);
    qemu_set_irq(s->pen_detect, 1);
    return 0;
}

