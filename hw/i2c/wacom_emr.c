static void wacom_init(Object *obj)
{
    WacomEMRState *s = WACOM_EMR(obj);
    s->reset_level = true;
    qdev_init_gpio_out_named(DEVICE(obj), &s->irq, "irq", 1);
    qdev_init_gpio_out_named(DEVICE(obj), &s->pen_detect, "pen-detect", 1);
    qdev_init_gpio_in_named(DEVICE(obj), wacom_gpio_reset, "reset", 1);
    object_property_add_uint64_ptr(obj, "queries", &s->queries, OBJ_PROP_FLAG_READ);
    object_property_add_uint64_ptr(obj, "descriptor-reads", &s->descriptor_reads, OBJ_PROP_FLAG_READ);
    object_property_add_uint64_ptr(obj, "resets", &s->resets, OBJ_PROP_FLAG_READ);
    object_property_add_uint64_ptr(obj, "sleep-commands", &s->sleep_commands, OBJ_PROP_FLAG_READ);
    object_property_add_uint64_ptr(obj, "unsupported-commands", &s->unsupported_commands, OBJ_PROP_FLAG_READ);
}

static void wacom_class_init(ObjectClass *oc, const void *data)
{
    DeviceClass *dc = DEVICE_CLASS(oc);
    I2CSlaveClass *sc = I2C_SLAVE_CLASS(oc);
    dc->vmsd = &wacom_vmstate;
    device_class_set_legacy_reset(dc, wacom_reset);
    sc->send = wacom_send;
    sc->recv = wacom_recv;
    sc->event = wacom_event;
}
static const TypeInfo wacom_info = {
    .name = TYPE_WACOM_EMR, .parent = TYPE_I2C_SLAVE,
    .instance_size = sizeof(WacomEMRState), .instance_init = wacom_init,
    .class_init = wacom_class_init,
};
static void wacom_register_types(void) { type_register_static(&wacom_info); }
